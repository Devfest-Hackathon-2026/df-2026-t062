import { test, expect, headers } from './support/fixtures.ts'

test('第5表: 追加→保存→再表示→履歴→PDF。保存失敗でも本文を失わない', async ({ page, ui, clientId }, info) => {
  if (ui === 'pad') {
    await page.getByRole('button', { name: 'アセスメント', exact: true }).click()
  } else await page.getByRole('button', { name: '＋ 書類を作る', exact: true }).click()
  await page.getByRole('menuitem', { name: /居宅介護支援経過 第5表/ }).click()
  await expect(page.getByRole('heading', { name: /さんの支援経過/ })).toBeVisible()
  await page.getByRole('button', { name: '＋ 支援経過を追加', exact: true }).click()
  await page.getByLabel('記録年月日', { exact: true }).fill('2026-11-22')
  await page.getByLabel('記録時刻', { exact: true }).fill('10:30')
  await page.getByLabel('作成年月日', { exact: true }).fill('2026-11-22')
  await page.getByLabel('項目・連絡方法', { exact: true }).fill('電話（受信）')
  const original = '本人から架空の相談あり。未決定のため次回確認する。'
  await page.getByLabel('記録内容', { exact: true }).fill(original)
  await page.getByRole('button', { name: '記録を保存', exact: true }).click()
  await expect(page.getByLabel('修正履歴')).toContainText('保存版 1')
  await page.getByLabel('記録内容', { exact: true }).fill('人が修正した架空の本文')
  await page.route('**/api/documents/*/save', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'test_failure', message: '検証用の保存失敗' }) }))
  await page.getByRole('button', { name: '記録を保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('検証用の保存失敗')
  await expect(page.getByLabel('記録内容', { exact: true })).toHaveValue('人が修正した架空の本文')
  await page.unroute('**/api/documents/*/save')
  await page.getByRole('button', { name: '記録を保存', exact: true }).click()
  await expect(page.getByLabel('修正履歴')).toContainText('保存版 2')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('修正履歴').selectOption('1')
  await expect(page.getByLabel('記録内容', { exact: true })).toHaveValue(original)
  await expect(page.getByLabel('記録内容', { exact: true })).toBeDisabled()
  const oldDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'この保存版のPDF', exact: true }).click()
  await oldDownload
  await page.getByLabel('修正履歴').selectOption('')
  await expect(page.getByLabel('記録内容', { exact: true })).toHaveValue('人が修正した架空の本文')
  await page.screenshot({ path: info.outputPath('support-progress.png'), fullPage: true })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '第5表PDF', exact: true }).click()
  expect((await download).suggestedFilename()).toContain('居宅介護支援経過')
  const data = await page.request.get('/api/clients/' + clientId + '/care-records', { headers })
  expect((await data.json()).records).toHaveLength(1)
  await page.getByRole('button', { name: '資料から下書きを作る', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '未確認の候補です' })).toBeVisible()
  await expect(page.getByLabel('記録内容', { exact: true })).toHaveValue('人が修正した架空の本文')
  const recordList = page.getByRole('complementary', { name: '支援経過の記録一覧', exact: true })
  const previousHeight = (await recordList.boundingBox())!.height
  let resumeRefresh!: () => void
  const refreshGate = new Promise<void>(resolve => { resumeRefresh = resolve })
  const listRoute = '**/api/clients/*/care-records?*'
  await page.route(listRoute, async route => { await refreshGate; await route.continue() })
  const refreshStarted = page.waitForRequest(r => r.method() === 'GET' && r.url().includes('/care-records?'))
  try {
    await page.getByRole('button', { name: '内容を確認して記録に採用', exact: true }).click()
    await refreshStarted
    await expect(page.getByLabel('記録内容', { exact: true })).toHaveValue('AIによる架空の下書き。未決定事項は次回確認する。')
    // 遅い一覧再取得中も、記録と保存ボタンの位置を保つ。
    await expect(recordList).toContainText('人が修正した架空の本文')
    expect((await recordList.boundingBox())!.height).toBeCloseTo(previousHeight, 0)
    await expect(page.getByLabel('修正履歴')).not.toContainText('保存版 3')
    const saved = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/save'))
    await page.getByRole('button', { name: '記録を保存', exact: true }).click()
    expect((await saved).ok()).toBeTruthy()
  } finally { resumeRefresh() }
  await expect(page.getByLabel('修正履歴')).toContainText('保存版 3')
  await page.getByRole('button', { name: '書類に戻る', exact: true }).click()
  await expect(page.getByRole('tablist', { name: '書類' }).or(page.getByRole('button', { name: 'アセスメント', exact: true }))).toBeVisible()
})

test('第4表: 出席者・検討内容・結論・残課題を分けて保存し、過去版を再現する', async ({ page, ui }, info) => {
  if (ui === 'pad') await page.getByRole('button', { name: 'アセスメント', exact: true }).click()
  else await page.getByRole('button', { name: '＋ 書類を作る', exact: true }).click()
  await page.getByRole('menuitem', { name: /サービス担当者会議の要点 第4表/ }).click()
  await page.getByRole('button', { name: '＋ 会議記録を追加', exact: true }).click()
  await page.getByLabel('開催日', { exact: true }).fill('2026-11-22')
  await page.getByLabel('開催場所', { exact: true }).fill('架空会議室')
  await page.getByLabel('開始時刻', { exact: true }).fill('14:00')
  await page.getByLabel('終了時刻', { exact: true }).fill('15:00')
  await page.getByLabel('開催回数', { exact: true }).fill('2')
  await page.getByLabel('本人の出席', { exact: true }).selectOption('出席')
  await page.getByLabel('家族の出席', { exact: true }).selectOption('欠席')
  await page.getByRole('button', { name: '出席者を追加', exact: true }).click()
  await page.getByLabel('出席者1の所属', { exact: true }).fill('架空訪問看護')
  await page.getByLabel('出席者1の職種', { exact: true }).fill('看護師')
  await page.getByLabel('出席者1の氏名', { exact: true }).fill('架空 一郎')
  await page.getByLabel('検討した項目', { exact: true }).fill('外出支援の頻度')
  await page.getByLabel('検討内容', { exact: true }).fill('週2回への変更を検討。合意には至っていない。')
  await page.getByLabel('結論', { exact: true }).fill('次回本人に確認することに合意。')
  await page.getByLabel('残された課題', { exact: true }).fill('変更の頻度は未決定。')
  await page.getByRole('button', { name: '記録を保存', exact: true }).click()
  await expect(page.getByLabel('修正履歴')).toContainText('保存版 1')
  await page.getByLabel('残された課題', { exact: true }).fill('本人の意向を確認後に調整。')
  await page.getByRole('button', { name: '記録を保存', exact: true }).click()
  await expect(page.getByLabel('修正履歴')).toContainText('保存版 2')
  await page.getByLabel('修正履歴').selectOption('1')
  await expect(page.getByLabel('残された課題', { exact: true })).toHaveValue('変更の頻度は未決定。')
  await expect(page.getByLabel('出席者1の氏名', { exact: true })).toHaveValue('架空 一郎')
  await expect(page.getByLabel('検討内容', { exact: true })).toBeDisabled()
  await page.getByLabel('修正履歴').selectOption('')
  await expect(page.getByLabel('残された課題', { exact: true })).toHaveValue('本人の意向を確認後に調整。')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '第4表PDF', exact: true }).click()
  expect((await download).suggestedFilename().normalize('NFC')).toContain('サービス担当者会議の要点')
  await page.getByRole('button', { name: '資料から下書きを作る', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '未確認の候補です' })).toBeVisible()
  await expect(page.getByLabel('残された課題', { exact: true })).toHaveValue('本人の意向を確認後に調整。')
  await page.getByRole('button', { name: '内容を確認して記録に採用', exact: true }).click()
  await expect(page.getByLabel('残された課題', { exact: true })).toHaveValue('AIによる架空の下書き。未決定事項は次回確認する。')
  await expect(page.getByLabel('結論', { exact: true })).toHaveValue('次回本人に確認することに合意。')
  await expect(page.getByLabel('修正履歴')).not.toContainText('保存版 3')
  await page.screenshot({ path: info.outputPath('meeting-record.png'), fullPage: true })
})
